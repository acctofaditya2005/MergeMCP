"""Regenerate docs/tools.md from the live server so the reference cannot drift.

python scripts/gen_tool_docs.py          # rewrite docs/tools.md
python scripts/gen_tool_docs.py --check  # exit 1 if it is out of date (used in CI)
"""

from __future__ import annotations

import asyncio
import sys
import tempfile
from pathlib import Path

from fastmcp import Client

from merge_mcp.config import Settings
from merge_mcp.server import build_services, create_server

OUT = Path(__file__).resolve().parent.parent / "docs" / "tools.md"
GROUPS = {
    "Discovery": ["find_issues_in_dependencies", "find_issues", "assess_issue"],
    "Workspace": [
        "start_workspace",
        "get_job",
        "get_playbook",
        "find_precedents",
        "list_workspaces",
        "delete_workspace",
    ],
    "Files": ["list_files", "read_file", "search_code", "edit_file", "write_file", "get_diff"],
    "Checks": ["start_check", "check_readiness"],
    "Handoff and follow-up": ["prepare_pull_request", "check_pull_request"],
}

RETURNS = {
    "find_issues": "IssueSearchResult",
    "find_issues_in_dependencies": "DependencyIssueResult",
    "assess_issue": "IssueAssessment",
    "start_workspace": "JobHandle",
    "get_job": "JobStatus",
    "get_playbook": "Playbook",
    "find_precedents": "PrecedentList",
    "list_workspaces": "list[Workspace]",
    "delete_workspace": "str",
    "list_files": "FileList",
    "read_file": "FileContent",
    "search_code": "SearchResult",
    "edit_file": "WriteResult",
    "write_file": "WriteResult",
    "get_diff": "DiffResult",
    "start_check": "JobHandle",
    "check_readiness": "Readiness",
    "prepare_pull_request": "PullRequestDraft",
    "check_pull_request": "PullRequestStatus",
}


def type_of(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        return " \\| ".join(type_of(s) for s in schema["anyOf"])
    if schema.get("type") == "array":
        return f"{type_of(schema.get('items', {}))}[]"
    return schema.get("type", "any")


def render_tool(tool) -> str:
    notes = []
    ann = tool.annotations
    if ann is not None:
        if ann.read_only_hint:
            notes.append("read-only")
        if ann.destructive_hint:
            notes.append("destructive")
        if ann.open_world_hint:
            notes.append("calls GitHub")
    returns = RETURNS[tool.name]
    lines = [f"### `{tool.name}`", "", " ".join(tool.description.split()), ""]
    props = tool.input_schema.get("properties", {})
    required = set(tool.input_schema.get("required", []))
    if props:
        lines += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
        for name, schema in props.items():
            default = (
                f" Default: `{schema['default']}`." if schema.get("default") is not None else ""
            )
            lines.append(
                f"| `{name}` | {type_of(schema)} | {'yes' if name in required else 'no'} | "
                f"{schema.get('description', '')}{default} |"
            )
        lines.append("")
    else:
        lines += ["No parameters.", ""]
    lines.append(f"Returns: `{returns}`" + (f" · {', '.join(notes)}" if notes else ""))
    return "\n".join(lines)


async def render() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        services = build_services(Settings(home=Path(tmp), sandbox="local"))
        async with Client(create_server(services)) as client:
            tools = {t.name: t for t in await client.list_tools()}
            prompts = await client.list_prompts()
            templates = await client.list_resource_templates()
    documented = [name for names in GROUPS.values() for name in names]
    missing = set(tools) - set(documented)
    if missing:
        raise SystemExit(f"Add these tools to GROUPS: {sorted(missing)}")
    parts = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/gen_tool_docs.py from the server's own schemas. "
        "Do not edit by hand. -->",
        "",
        f"The server exposes {len(tools)} tools, {len(templates)} resource template and "
        f"{len(prompts)} prompt. Return types are the Pydantic models in "
        "[`models.py`](../src/merge_mcp/models.py).",
        "",
    ]
    for group, names in GROUPS.items():
        parts += [f"## {group}", ""]
        for name in names:
            parts += [render_tool(tools[name]), ""]
    parts += ["## Resources", ""]
    for t in templates:
        parts += [f"- `{t.uri_template}`: {t.description}"]
    parts += ["", "## Prompts", ""]
    for p in prompts:
        args = ", ".join(a.name for a in p.arguments or [])
        parts += [f"- `{p.name}({args})`: {p.description}"]
    return "\n".join(parts) + "\n"


def main() -> None:
    text = asyncio.run(render())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit("docs/tools.md is out of date. Run scripts/gen_tool_docs.py.")
        print("docs/tools.md is up to date.")
        return
    OUT.write_text(text)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
